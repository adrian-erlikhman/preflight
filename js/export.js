// export.js — turn a Preflight report into Markdown, a compact summary for the
// assistant, and a README badge.

import { GROUPS, PROFILE, SECTIONS, sectionUrl } from "./checks.js";

const ICON = { pass: "✅", fail: "❌", warn: "⚠️", info: "ℹ️", skip: "⏭️" };

/**
 * A Markdown report a developer can paste into an issue or a pull request.
 *
 * :param report: The report from runPreflight.
 * :param pageUrl: Preflight's address, for the link back.
 * :return: Markdown text.
 */
export function toMarkdown(report, pageUrl = "") {
  const lines = [];
  const s = report.summary;
  lines.push(`# Preflight report: ${report.base || report.target}`);
  lines.push("");
  lines.push(`Checked against the [${PROFILE.name} spec, profile ${PROFILE.version}](${PROFILE.url}) on ${report.finishedAt?.slice(0, 10) || ""}.`);
  lines.push("");
  lines.push(`**${s.must.fail ? `${s.must.fail} required check${s.must.fail === 1 ? "" : "s"} failed` : "All required checks passed"}**, ${s.must.pass} passed. ${s.should.warn} recommendation${s.should.warn === 1 ? "" : "s"} to review.`);
  lines.push("");
  for (const verdict of Object.values(s.verdicts)) lines.push(`- ${verdict.ok ? "✅" : "❌"} ${verdict.label}`);
  lines.push("");
  for (const group of GROUPS) {
    const checks = report.checks.filter((c) => c.group === group.id);
    if (!checks.length) continue;
    lines.push(`## ${group.title}`);
    lines.push("");
    for (const c of checks) {
      const where = c.network ? ` (${c.network})` : "";
      const section = SECTIONS[c.section] && c.section !== "challenge" ? ` [§${c.section}](${sectionUrl(c.section)})` : "";
      lines.push(`- ${ICON[c.status] || ""} **${c.title}**${where}${section}: ${c.detail}`);
      for (const e of (c.evidence || []).slice(0, 8)) lines.push(`  - \`${String(e).replace(/`/g, "'")}\``);
      if (c.fix && c.status !== "pass") lines.push(`  - Fix: ${c.fix}`);
    }
    lines.push("");
  }
  lines.push("## Files read");
  lines.push("");
  lines.push("| File | Result |");
  lines.push("| --- | --- |");
  for (const f of report.files) lines.push(`| ${f.url} | ${fileResult(f)} |`);
  lines.push("");
  if (pageUrl) lines.push(`Generated by [Preflight](${pageUrl}).`);
  return lines.join("\n");
}

export function fileResult(file) {
  if (file.ok) return `${file.status} · ${file.bytes.toLocaleString()} chars`;
  if (file.corsBlocked) return "blocked: no CORS header";
  if (file.unreachable) return "unreachable";
  return file.status ? `HTTP ${file.status}` : file.error || "failed";
}

/**
 * The report in the shape the assistant reads: everything that needs attention in full,
 * passed checks as titles only, so the tool result stays small.
 *
 * :param report: The report from runPreflight.
 * :return: Plain JSON data.
 */
export function compactReport(report) {
  if (!report) return { ok: false, reason: "No site has been checked on this page yet." };
  const s = report.summary;
  return {
    ok: true,
    site_base: report.base,
    url_checked: report.target,
    read_as: report.interpretation,
    requested_network: report.requestedNetwork,
    spec: `${PROFILE.name} profile ${PROFILE.version}`,
    required: { passed: s.must.pass, failed: s.must.fail },
    recommended: { passed: s.should.pass, to_review: s.should.warn },
    verdicts: Object.fromEntries(Object.entries(s.verdicts).map(([k, v]) => [v.label, v.ok])),
    ready_for_other_sites: s.ready,
    networks: report.networks.map((n) => ({
      name: n.name, front_agent: n.front_man, file: n.hocon,
      agents: n.agents.map((a) => a.name), peer_references: n.externals, mcp_servers: n.mcps,
      link_slots: n.linkSlots, sample_queries: n.sampleQueries.slice(0, 6),
    })),
    needs_attention: report.checks
      .filter((c) => c.status === "fail" || c.status === "warn")
      .map((c) => ({
        id: c.id, level: c.level === "must" ? "required" : "recommended", status: c.status,
        title: c.title, network: c.network || undefined, spec_section: c.section,
        detail: c.detail, evidence: (c.evidence || []).slice(0, 6), fix: c.fix || undefined,
      })),
    passed: report.checks.filter((c) => c.status === "pass").map((c) => c.title),
    notes: report.checks.filter((c) => c.status === "info").map((c) => `${c.title}: ${c.detail}`).slice(0, 10),
    files_read: report.files.map((f) => ({ role: f.role, url: f.url, result: fileResult(f) })),
    contact_declined: report.declined,
  };
}

/**
 * A static README badge and the Markdown that links it back to this report.
 *
 * :param report: The report.
 * :param pageUrl: Preflight's address.
 * :return: {imageUrl, markdown, label, message, color}.
 */
export function badgeFor(report, pageUrl) {
  const failed = report.summary.must.fail;
  const message = failed ? `${failed} failing` : `MVP ${PROFILE.version} passing`;
  const color = failed ? "b91c1c" : "15803d";
  const esc = (text) => encodeURIComponent(text.replace(/-/g, "--").replace(/_/g, "__"));
  const imageUrl = `https://img.shields.io/badge/${esc("preflight")}-${esc(message)}-${color}`;
  const link = `${pageUrl}?url=${encodeURIComponent(report.target)}`;
  return { imageUrl, markdown: `[![Preflight: ${message}](${imageUrl})](${link})`, message, color };
}
